console.log('number' + 3 + 3);
// Результат: 'number33'
// 1. 'number' + 3 -> рядок 'number3' (плюс з рядком склеює).
// 2. 'number3' + 3 -> рядок 'number33'.

console.log(null + 3);
// Результат: 3
// 1. null перетворюється на 0.
// 2. 0 + 3 = 3.

console.log(5 && "qwerty");
// Результат: "qwerty"
// 1. Оператор && (І) шукає першу брехню (false).
// 2. 5 - це правда (true), тому йдемо далі.
// 3. Повертається останнє значення -> "qwerty".

console.log(+'40' + +'2' + "hillel");
// Результат: "42hillel"
// 1. +'40' перетворюється на число 40.
// 2. +'2' перетворюється на число 2.
// 3. 40 + 2 = 42.
// 4. 42 + "hillel" -> склеювання -> "42hillel".

console.log('10' - 5 === 6);
// Результат: false
// 1. '10' - 5 -> рядок стає числом при мінусі -> 5.
// 2. 5 === 6 -> це неправда (false).

console.log(true + false);
// Результат: 1
// 1. true стає 1.
// 2. false стає 0.
// 3. 1 + 0 = 1.

console.log('4px' - 3);
// Результат: NaN
// 1. '4px' не можна перетворити на чисте число (букви заважають).
// 2. Отримуємо NaN (Not a Number).

console.log('4' - 3);
// Результат: 1
// 1. '4' перетворюється на число 4 (бо мінус).
// 2. 4 - 3 = 1.

console.log('6' + 3 ** 0);
// Результат: "61"
// 1. Пріоритет у степеня (**). 3 у степені 0 = 1.
// 2. '6' + 1 -> склеювання -> "61".

console.log(12 / '6');
// Результат: 2
// 1. '6' стає числом 6 (бо ділення).
// 2. 12 / 6 = 2.

console.log('10' + (5 === 6));
// Результат: "10false"
// 1. Дужки перші: 5 === 6 -> це false.
// 2. '10' + false -> склеювання -> "10false".

console.log(null == '');
// Результат: false
// 1. null дорівнює тільки null або undefined.
// 2. null не дорівнює порожньому рядку.

console.log(3 ** (9 / 3));
// Результат: 27
// 1. Дужки: 9 / 3 = 3.
// 2. 3 у степені 3 (3 * 3 * 3) = 27.

console.log(!!'false' == !!'true');
// Результат: true
// 1. !!'false' -> непорожній рядок це true.
// 2. !!'true' -> непорожній рядок це true.
// 3. true == true -> результат true.

console.log(0 || '0' && 1);
// Результат: 1
// 1. Пріоритет у && вищий ніж у ||.
// 2. '0' && 1 -> '0' це правда, тому повертає останнє -> 1.
// 3. Тепер вираз: 0 || 1.
// 4. 0 це брехня, тому йдемо далі і повертаємо 1.

console.log((+null == false) < 1);
// Результат: false
// 1. +null стає 0.
// 2. 0 == false -> це правда (true).
// 3. true < 1 -> true стає 1.
// 4. 1 < 1 -> це неправда (false).

console.log(false && true || true);
// Результат: true
// 1. Спочатку &&: false && true -> false (бо перше false).
// 2. Потім ||: false || true -> true (знайшли правду).

console.log(false && (false || true));
// Результат: false
// 1. Дужки: (false || true) -> true.
// 2. false && true -> false (бо перше false).

console.log((+null == false) < 1 ** 5);
// Результат: false
// 1. Степінь: 1 ** 5 = 1.
// 2. +null стає 0.
// 3. 0 == false -> true.
// 4. true < 1 -> (1 < 1) -> false.