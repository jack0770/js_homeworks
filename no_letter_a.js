// Масив слів для перевірки (з прикладу)
var words = ["Wonderful", "Joyful", "Happiness", "Time", "Task", "Apple"];

// Регулярний вираз:
// ^       -> Початок слова (рядка)
// [^aA]   -> Будь-який символ, КРІМ 'a' або 'A' (квадратні дужки з ^ всередині - це заперечення)
// {6,}    -> Цей символ має повторюватися 6 або більше разів
// $       -> Кінець слова (рядка)

var pattern = /^[^aA]{6,}$/;

// Перевіряємо кожне слово
for (var i = 0; i < words.length; i++) {
    var word = words[i];
    
    if (pattern.test(word)) {
        console.log(word + " -> ПІДХОДИТЬ (6+ літер і немає 'A')");
    } else {
        console.log(word + " -> не підходить");
    }
}

// Очікуваний результат в консолі:
// Wonderful -> ПІДХОДИТЬ
// Joyful -> ПІДХОДИТЬ
// Happiness -> не підходить (бо є 'a')
// Time -> не підходить (мало літер)
// Task -> не підходить
// Apple -> не підходить